// The full view's width table, from pi-tui's (§10 T4 of the Duo plan).
//
// The page at `/draw/` lays a row out in cells, and which characters take two
// cells or none is pi-tui's to say: it is what the window measured when it drew
// the row, and what `terminal.ts` reads when it draws the README's pictures.
// A browser cannot import pi-tui, so its answer for every code point is written
// out once into `packages/web/src/assets/full-widths.js`, and
// `test/full-cells.test.ts` holds that file equal to what pi-tui says now —
// a pi-tui that moves its table fails the test until this is run again:
//
//   node packages/app/scripts/full-widths.ts

import { writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { visibleWidth } from '@earendil-works/pi-tui'

export const WIDTHS_FILE = fileURLToPath(
  new URL('../../web/src/assets/full-widths.js', import.meta.url),
)

/**
 * Each code point a drawn row can hold that anything has been assigned: the
 * first four planes and the fifteenth, where the tags and the selectors are.
 * The ten between hold nothing yet and the last two are private use — one cell
 * to every width table there is — and measuring them would only make the test
 * that runs this four times slower. A row's controls are stepped over before
 * anything is measured.
 */
export function* points(): Generator<number> {
  for (let c = 0x20; c <= 0xe0fff; c++) {
    if (c === 0x40000) c = 0xe0000
    if (c === 0x7f || (c >= 0xd800 && c <= 0xdfff)) continue
    yield c
  }
}

/** `c` at `width` added to a flat `[from, to, width, …]`, joining the run it continues. */
function extend(runs: number[], c: number, width: number): void {
  const at = runs.length
  if (at > 0 && runs[at - 2] === c - 1 && runs[at - 1] === width) runs[at - 2] = c
  else runs.push(c, c, width)
}

/** Every run of code points pi-tui does not measure as one cell, alone. */
export function widthTable(): number[] {
  const out: number[] = []
  for (const c of points()) {
    const width = visibleWidth(String.fromCodePoint(c))
    if (width !== 1) extend(out, c, width)
  }
  return out
}

/**
 * The code points pi-tui measures otherwise when something joins them that
 * does not make an emoji — a combining grapheme joiner stands in for any: it
 * reads such a glyph by its first code point's East Asian width, which for the
 * newest emoji is older than the emoji data that makes one two cells alone.
 * Only a code point two cells alone is asked: one cell is what either reading
 * gives every other.
 */
export function joinedTable(widths: readonly number[] = widthTable()): number[] {
  const out: number[] = []
  for (let i = 0; i < widths.length; i += 3) {
    if (widths[i + 2] !== 2) continue
    const [from = 0, to = 0] = widths.slice(i, i + 2)
    for (let c = from; c <= to; c++) {
      const width = Math.max(1, visibleWidth(`${String.fromCodePoint(c)}\u034f`))
      if (width !== 2) extend(out, c, width)
    }
  }
  return out
}

function hexLines(table: readonly number[]): string[] {
  const lines: string[] = []
  for (let i = 0; i < table.length; i += 3) {
    const [from = 0, to = 0, width = 0] = table.slice(i, i + 3)
    lines.push(`  0x${from.toString(16)}, 0x${to.toString(16)}, ${width},`)
  }
  return lines
}

/** The file's text: each table as hex, three to a line. */
export function widthsSource(widths: readonly number[], joined: readonly number[]): string {
  return [
    '// Generated by `node packages/app/scripts/full-widths.ts` from pi-tui’s',
    '// width table — never edited by hand: `test/full-cells.test.ts` holds it',
    '// equal to what pi-tui says. Each table is runs of code points as',
    '// `from, to, width`.',
    '',
    '// Every run not one cell wide alone: two for a wide one, nought for one that',
    '// joins the glyph before it.',
    '// biome-ignore format: three to a line is the table.',
    'export const WIDTHS = [',
    ...hexLines(widths),
    ']',
    '',
    '// The runs measured otherwise when something that makes no emoji joins them.',
    '// biome-ignore format: three to a line is the table.',
    'export const JOINED = [',
    ...hexLines(joined),
    ']',
    '',
  ].join('\n')
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const widths = widthTable()
  writeFileSync(WIDTHS_FILE, widthsSource(widths, joinedTable(widths)))
  console.log(`wrote ${WIDTHS_FILE}`)
}
